# -*- coding: utf-8 -*-
import json,datetime
E=json.load(open('events.json'))
M={ (r['event_id'],r['ticker']):r for r in json.load(open('measurements.json')) }
def q(s):
    if s is None: return None
    return '"'+str(s).replace('\\','\\\\').replace('"','\\"').replace('\n',' ')+'"'
L=[]
A=L.append
A('# 国内暗号資産交換業者の「新規取扱のお知らせ」発表履歴 (TRA-66)')
A('#')
A('# 全項目、各社の公告ページ／プレスリリース（一次情報）を 2026-11-14 に実際に取得して確認した値のみを記載する。')
A('# 確認できなかった項目は「キーを省略」し、report 側に unknown とその理由を書く。')
A('# 二次情報（まとめ記事等）由来の値はこのファイルには入れない。')
A('#')
A('# 対象期間: 2024-11-14 〜 2026-11-14 (直近24ヶ月)')
A('# 対象業者: bitbank / GMOコイン / bitFlyer / Coincheck / SBI VCトレード / BITPOINT')
A('#   OKCoinJapan: 取得不能 (robots.txt が ClaudeBot 等に対し Disallow: /。公告パスは許可リスト外)')
A('#   DMM Bitcoin: 取得不能 (事業終了。bitcoin.dmm.com 接続不能。口座・資産はSBI VCトレードへ移管)')
A('#')
A('# announce_utc は「分単位まで一次情報で確定できた発表時刻」のみ記載する。')
A('#   time_precision = "second" … 発表時刻が秒単位で取得できた (bitbank: microCMS publishedAt /')
A('#                               Coincheck: STUDIO publishedAt / GMO: 公式RSS pubDate)')
A('#   time_precision = "hour"   … 時までしか取得できなかった (announce_jst_hour に記載)')
A('#   time_precision = "date"   … 日付のみ (announce_date_jst に記載)')
A('#')
A('# kind = "new_listing"      … その業者で新たに取扱う銘柄の発表')
A('#        "migration"        … 既に取扱中の銘柄のトークン移行・改称 (RNDR→RENDER, MKR→SKY, LSKチェーン移行)')
A('#        "new_service_type" … 既に取扱中の銘柄への取引種類追加 (板取引・信用取引の追加)')
A('#')
A('# first_in_jp は「国内初上場かどうか」。発表文に「国内初」「日本初」の明示がある場合、')
A('#   および他の国内業者の取扱銘柄一覧に当該時点で存在しないことを確認できた場合に true。')
A('#')
A('# ref = 海外の参照市場。"binance" は現物 USDT ペア、"hyperliquid" は perp。')
A('#   ref を省略している銘柄は海外参照市場が存在せず価格反応を測れない (no_ref_reason 参照)。')
A('')
for e in E:
    A('[[announcements]]')
    A(f'id = {q(e["id"])}')
    A(f'venue = {q(e["venue"])}')
    A(f'kind = {q(e["kind"])}')
    A(f'title = {q(e["title"])}')
    if e.get('announce_utc'): A(f'announce_utc = {q(e["announce_utc"])}')
    if e.get('announce_jst_hour'): A(f'announce_jst_hour = {q(e["announce_jst_hour"])}')
    if e.get('announce_date_jst'): A(f'announce_date_jst = {q(e["announce_date_jst"])}')
    A(f'time_precision = {q(e["time_precision"])}')
    if e.get('start_date_jst') and e['start_date_jst']!='unknown': A(f'start_date_jst = {q(e["start_date_jst"])}')
    if e.get('start_utc'): A(f'start_utc = {q(e["start_utc"])}')
    if e.get('start_precision') and e['start_precision']!='unknown': A(f'start_precision = {q(e["start_precision"])}')
    if e.get('start_note'): A(f'start_note = {q(e["start_note"])}')
    A(f'listing_type = {q(e["listing_type"])}')
    A(f'source_url = {q(e["source"])}')
    if e.get('is_migration'): A('is_migration = true')
    if e.get('note'): A(f'note = {q(e["note"])}')
    for a in e['assets']:
        A('')
        A(f'  [[announcements.assets]]')
        A(f'  ticker = {q(a["ticker"])}')
        A(f'  name_ja = {q(a["name"])}')
        if a.get('chain') and a['chain']!='unknown': A(f'  chain = {q(a["chain"])}')
        A(f'  first_in_jp = {"true" if a.get("first_in_jp") else "false"}')
        if a.get('ref'):
            A(f'  ref = {q(a["ref"])}')
            A(f'  ref_symbol = {q(a["ref_symbol"])}')
        A(f'  hyperliquid_perp = {"true" if a.get("hl_perp") else "false"}')
        if a.get('hl_symbol'): A(f'  hyperliquid_symbol = {q(a["hl_symbol"])}')
        if a.get('no_ref_reason'): A(f'  no_ref_reason = {q(a["no_ref_reason"])}')
        if a.get('identity_note'): A(f'  identity_note = {q(a["identity_note"])}')
        m=M.get((e['id'],a['ticker']))
        if m and m['coverage_T-1h_T+4h']>=0.9:
            r=m['returns'].get('T+15m->T+24h')
            if r and r.get('excess_net') is not None:
                A(f'  measured_main_excess_net = {r["excess_net"]}   # エントリT+15分/イグジットT+24h、往復0.29%控除後・BTC超過')
            pre=m['pre_T-24h_to_T-5m'].get('excess')
            if pre is not None: A(f'  measured_pre_T24h_to_T5m_excess = {pre}')
        elif m:
            A(f'  measured = false   # {"; ".join(m["flags"])}')
    A('')
open('jp_listings.toml','w').write('\n'.join(L)+'\n')
print("lines",len(L))
